import assert from "node:assert/strict";
import { build } from "esbuild";

const values = new Map();
let fail = false;
let changes = 0;
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => { if (fail) throw new Error("Storage full"); values.set(key, value); } };
globalThis.window = { dispatchEvent: () => { changes++; } };
const output = await build({ entryPoints: ["src/lib/branding.ts"], bundle: true, write: false, platform: "node", format: "esm" });
const { readBrand, saveBrand, logoFromFile, DEFAULT_BRAND, BRAND_KEY } = await import(`data:text/javascript;base64,${Buffer.from(output.outputFiles[0].text).toString("base64")}`);
assert.deepEqual(readBrand(), DEFAULT_BRAND);
saveBrand({ name: "  我的笔记  " });
assert.equal(readBrand().name, "我的笔记");
assert.equal(changes, 1);
saveBrand({ logo: "data:image/png;base64,aGVsbG8=" });
assert.equal(readBrand().name, "我的笔记");
assert.ok(readBrand().logo.startsWith("data:image/png"));
saveBrand({ name: DEFAULT_BRAND.name });
assert.ok(readBrand().logo.startsWith("data:image/png"));
saveBrand({ logo: DEFAULT_BRAND.logo });
assert.deepEqual(readBrand(), DEFAULT_BRAND);
assert.throws(() => saveBrand({ name: " " }), /名称/);
assert.throws(() => saveBrand({ name: "a".repeat(33) }), /名称/);
assert.throws(() => saveBrand({ logo: "javascript:alert(1)" }), /Logo/);
assert.throws(() => saveBrand({ logo: "data:image/png;base64," + "a".repeat(500_000) }), /Logo/);
await assert.rejects(() => logoFromFile({ name: "not-a-logo.pdf", type: "application/pdf", size: 2 }), /图片/);
await assert.rejects(() => logoFromFile({ name: "large.png", type: "image/png", size: 6 * 1024 * 1024 }), /5 MB/);
fail = true;
assert.throws(() => saveBrand({ name: "失败不丢失原设置" }), /Storage full/);
assert.deepEqual(readBrand(), DEFAULT_BRAND);
values.set(BRAND_KEY, "broken-json");
assert.deepEqual(readBrand(), DEFAULT_BRAND);
console.log("Passed: workspace name/logo persistence, independent reset, malformed data, limits and storage failures.");
delete globalThis.localStorage; delete globalThis.window;
